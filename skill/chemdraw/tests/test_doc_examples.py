"""Every example in the hand-written Skill pages is classified, and the runnable ones run.

A fenced ``json`` block, or any fenced block that mentions ``cdx.py``, must sit directly under an
HTML comment that says what it is (the comment does not show in rendered Markdown):

``<!-- example: call TOOL -->``
    the JSON block is the argument object of TOOL; it is called in-process in a scratch folder,
    offline, without ChemDraw, Office or optional engines, and must return without ``ok: false``.
``<!-- example: call TOOL arg=NAME -->``
    the block is passed to TOOL as the argument NAME (a JSON block as an object, other text as a string).
``<!-- example: call TOOL file=NAME KEY=VALUE ... -->``
    the block is written to a file and its path passed as NAME; each KEY=VALUE adds a string argument
    (for a tool that reads a spec or manifest file, such as ``compose_chemical_figure``).
``<!-- example: call TOOL needs=chemdraw -->`` (or ``needs=network``, ``needs=office``, ``needs=engine``)
    the arguments are only validated against TOOL's input schema; nothing runs.
``<!-- example: commands -->``
    a shell block: every ``cdx.py`` line must name a real subcommand, ``cdx.py call TOOL`` a
    registered tool, and a literal ``--json '{...}'`` must validate against that tool's schema.
``<!-- example: fragment -->``
    part of a larger object, a response shape or a configuration file; checked for valid JSON only
    when it is a ``json`` block that parses as a whole object.

An unmarked block fails, so every new example has to be classified. Generated pages (their first
lines say "Generated by" or "Do not hand-edit") and the ``inventory/`` shards are skipped.

Relative paths in examples resolve against a scratch copy of a small fixture folder; ``<abs>`` is
replaced by that folder's absolute path.
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import shlex
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

import pytest


SKILL_ROOT = Path(__file__).resolve().parent.parent
REFERENCES = SKILL_ROOT / "references"
FENCE = re.compile(r"^\s*```(\S*)\s*$")
MARKER = re.compile(r"^\s*<!--\s*example:\s*(.*?)\s*-->\s*$")
GENERATED = re.compile(r"do not (hand-)?edit|generated by", re.IGNORECASE)
SUBCOMMAND = re.compile(r"sub\.add_parser\('([a-z-]+)'")
NEEDS = {"chemdraw", "network", "office", "engine"}


def hand_written_pages() -> list[Path]:
    pages = [SKILL_ROOT / "SKILL.md"]
    for page in sorted(REFERENCES.glob("*.md")):
        head = "\n".join(page.read_text(encoding="utf-8").splitlines()[:12])
        if not GENERATED.search(head):
            pages.append(page)
    return pages


def example_blocks(page: Path) -> list[dict]:
    """Fenced blocks that are JSON or mention cdx.py, with the marker comment above them."""
    lines = page.read_text(encoding="utf-8").splitlines()
    blocks, index = [], 0
    while index < len(lines):
        opened = FENCE.match(lines[index])
        if not opened:
            index += 1
            continue
        end = index + 1
        while end < len(lines) and not lines[end].strip().startswith("```"):
            end += 1
        body = "\n".join(lines[index + 1:end])
        lang = opened.group(1)
        marker = MARKER.match(lines[index - 1]) if index else None
        if lang == "json" or "cdx.py" in body or marker:
            blocks.append({
                "where": f"{page.name}:{index + 1}",
                "lang": lang,
                "body": body,
                "marker": marker.group(1) if marker else None,
            })
        index = end + 1
    return blocks


def parse_marker(text: str) -> dict:
    words = text.split()
    if not words or words[0] not in ("call", "commands", "fragment"):
        raise ValueError(f"unknown example marker {text!r}")
    if words[0] != "call":
        return {"kind": words[0]}
    if len(words) < 2:
        raise ValueError("`call` needs a tool name")
    marker = {"kind": "call", "tool": words[1], "arg": None, "file": None, "needs": None, "extra": {}}
    for word in words[2:]:
        key, _, value = word.partition("=")
        if not value:
            raise ValueError(f"marker option {word!r} needs a value")
        if key == "needs":
            if value not in NEEDS:
                raise ValueError(f"needs= takes one of {sorted(NEEDS)}")
            marker["needs"] = value
        elif key in ("arg", "file"):
            marker[key] = value
        else:
            marker["extra"][key] = value
    if marker["arg"] and marker["file"]:
        raise ValueError("give arg= or file=, not both")
    return marker


def arguments_for(marker: dict, block: dict) -> tuple[dict, dict]:
    """The tool arguments, and the files to write into the work folder first."""
    value = json.loads(block["body"]) if block["lang"] == "json" else block["body"] + "\n"
    files = {}
    if marker["arg"]:
        arguments = {marker["arg"]: value}
    elif marker["file"]:
        name = "example-input" + (".json" if block["lang"] == "json" else ".txt")
        files[name] = block["body"] + "\n"
        arguments = {marker["file"]: f"<abs>/{name}"}
    else:
        arguments = value
    arguments.update(marker["extra"])
    return arguments, files


ALL_BLOCKS = [block for page in hand_written_pages() for block in example_blocks(page)]


def _fixtures(root: Path) -> None:
    """Small grounded inputs the examples name by relative path."""
    from rdkit import Chem
    from rdkit.Chem import AllChem

    from cdxml_toolkit.mcp_runtime.tool_registry import build_registry

    def molfile(path: str, smiles: str) -> None:
        mol = Chem.MolFromSmiles(smiles)
        AllChem.Compute2DCoords(mol)
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(Chem.MolToMolBlock(mol), encoding="utf-8")

    for path in ("work/verified.mol", "verified_structure.mol", "A-corrected.mol"):
        molfile(path, "CC(=O)Oc1ccccc1C(=O)O")
    scheme = build_registry()["render_scheme"].function
    (root / "work").mkdir(exist_ok=True)
    result = scheme(
        compact_text='SA{OC(=O)c1ccccc1O} + Ac2O{CC(=O)OC(C)=O} --> ASP{CC(=O)Oc1ccccc1C(=O)O}\n  below: "rt, 2 h"\n',
        output_path=str(root / "work" / "scheme.cdxml"),
    )
    if isinstance(result, str):
        result = json.loads(result)
    assert result.get("ok"), result
    for copy in ("work/series.cdxml", "original.cdxml", "figure.cdxml"):
        shutil.copyfile(root / "work" / "scheme.cdxml", root / copy)
    (root / "results.csv").write_text(
        "series,label,smiles,yield,ee\npara,3a,Cc1ccc(cc1)C(=O)N,88%,95%\npara,3b,NC(=O)c1ccccc1,91%,\n",
        encoding="utf-8",
    )


class _Runtime:
    """The tool registry, input schemas and fixture folder, built once for the module."""

    registry = None
    schemas: dict = {}
    fixtures: Path | None = None
    saved_env: dict = {}

    @classmethod
    def start(cls) -> None:
        if cls.registry is not None:
            return
        cls.base = Path(tempfile.mkdtemp(prefix="doc-examples-"))
        isolate = {
            "CHEMDRAW_OFFLINE": "1",
            "CHEMDRAW_ACCEL": "off",
            "CHEMDRAW_ENGINE_HOME": str(cls.base / "no-engines"),
            "CHEMDRAW_MAPPER_HOME": str(cls.base / "no-mappers"),
        }
        cls.saved_env = {key: os.environ.get(key) for key in isolate}
        os.environ.update(isolate)
        from cdxml_toolkit.mcp_runtime import mcp_server
        from cdxml_toolkit.mcp_runtime.tool_registry import build_registry

        cls.registry = build_registry()
        server = mcp_server.build_server(profile="full")
        # The MCP SDK names the field inputSchema (1.x) or input_schema (2.x server-side Tool).
        cls.schemas = {
            tool.name: getattr(tool, "inputSchema", None) or getattr(tool, "input_schema")
            for tool in asyncio.run(server.list_tools())
        }
        cls.fixtures = cls.base / "fixtures"
        cls.fixtures.mkdir()
        _fixtures(cls.fixtures)

    @classmethod
    def stop(cls) -> None:
        for key, value in cls.saved_env.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value
        if cls.registry is not None:
            shutil.rmtree(cls.base, ignore_errors=True)


