def _validate(tool: str, arguments: dict) -> None:
    import jsonschema

    schema = _Runtime.schemas.get(tool)
    if schema is None:
        raise AssertionError(f"{tool} is not a registered tool")
    if "kwargs" in schema.get("required", []):
        # A Python **kwargs parameter appears in the listed schema as a required "kwargs" property;
        # the function itself takes the documented keywords directly.
        schema = {**schema, "required": [name for name in schema["required"] if name != "kwargs"]}
    jsonschema.validate(arguments, schema)


class _NoNativeApplications:
    """Refuse COM dispatch while an example runs, so nothing can start ChemDraw or Office."""

    def __enter__(self):
        self.patched = []
        try:
            import win32com.client as client  # type: ignore[import-not-found]
        except ImportError:
            return self

        def refuse(*args, **kwargs):
            raise RuntimeError("documentation examples must not start ChemDraw or Office")

        for name in ("Dispatch", "DispatchEx", "GetActiveObject", "GetObject"):
            if hasattr(client, name):
                self.patched.append((client, name, getattr(client, name)))
                setattr(client, name, refuse)
        return self

    def __exit__(self, *exc):
        for owner, name, original in self.patched:
            setattr(owner, name, original)
        return False


def _call(tool: str, arguments: dict, files: dict) -> dict:
    spec = _Runtime.registry[tool]
    if any(arguments.get(key) is True for key in ("render", "native_render", "render_pdf_preview")):
        raise AssertionError(f"{tool}: rendering needs ChemDraw or Office; mark the example needs=chemdraw")
    work = Path(tempfile.mkdtemp(dir=_Runtime.base, prefix="run-"))
    shutil.copytree(_Runtime.fixtures, work, dirs_exist_ok=True)
    for name, text in files.items():
        (work / name).write_text(text, encoding="utf-8")
    arguments = json.loads(json.dumps(arguments).replace("<abs>", work.as_posix()))
    previous = Path.cwd()
    os.chdir(work)
    try:
        with _NoNativeApplications():
            result = spec.function(**arguments)
    finally:
        os.chdir(previous)
    if isinstance(result, str):
        try:
            result = json.loads(result)
        except ValueError:
            return {"ok": True, "text": result}
    return result if isinstance(result, dict) else {"ok": True, "value": result}


def _cdx_lines(body: str) -> list[str]:
    commands = []
    for raw in body.splitlines():
        line = raw.split("  #", 1)[0].strip()
        while re.match(r"^[A-Z_]+=\S+\s", line):  # leading environment assignments
            line = line.split(None, 1)[1]
        if line.startswith("cdx.py "):
            commands.append(line)
    return commands


class MarkerTests(unittest.TestCase):
    def test_examples_were_found(self):
        self.assertGreater(len(ALL_BLOCKS), 40)

    def test_every_example_is_classified(self):
        unmarked = [block["where"] for block in ALL_BLOCKS if block["marker"] is None]
        self.assertEqual(unmarked, [], "put an <!-- example: ... --> comment on the line above each block")

    def test_markers_are_well_formed(self):
        broken = []
        for block in ALL_BLOCKS:
            if block["marker"] is None:
                continue
            try:
                marker = parse_marker(block["marker"])
            except ValueError as exc:
                broken.append(f"{block['where']}: {exc}")
                continue
            if marker["kind"] == "commands" and "cdx.py" not in block["body"]:
                broken.append(f"{block['where']}: `commands` block has no cdx.py line")
            if marker["kind"] == "call" and not (marker["arg"] or marker["file"]) and block["lang"] != "json":
                broken.append(f"{block['where']}: `call` without arg= needs a json block")
        self.assertEqual(broken, [])


CALLS = [block for block in ALL_BLOCKS if block["marker"] and block["marker"].startswith("call ")]
COMMANDS = [block for block in ALL_BLOCKS if block["marker"] == "commands"]


@pytest.mark.parametrize("block", CALLS, ids=[block["where"] for block in CALLS])
def test_runnable_example_is_accepted(block):
    _Runtime.start()
    marker = parse_marker(block["marker"])
    arguments, files = arguments_for(marker, block)
    _validate(marker["tool"], arguments)
    if marker["needs"]:
        return  # needs ChemDraw, the network, Office or an engine: the schema check is all that runs here
    result = _call(marker["tool"], arguments, files)
    assert result.get("ok") is not False, json.dumps(result, default=str)[:1500]


@pytest.mark.parametrize("block", COMMANDS, ids=[block["where"] for block in COMMANDS])
def test_command_example_names_real_commands_and_tools(block):
    _Runtime.start()
    source = (SKILL_ROOT / "scripts" / "cdx.py").read_text(encoding="utf-8")
    subcommands = set(SUBCOMMAND.findall(source))
    for line in _cdx_lines(block["body"]):
        words = line.split()
        assert words[1] in subcommands, line
        if words[1] != "call" or len(words) < 3 or not re.fullmatch(r"[a-z0-9_]+", words[2]):
            continue  # a usage line such as `cdx.py call TOOL ...`
        assert words[2] in _Runtime.schemas, f"{words[2]} is not a registered tool"
        try:
            argv = shlex.split(line)
        except ValueError:
            continue
        if "--json" in argv:
            payload = argv[argv.index("--json") + 1]
            if "<" not in payload:
                _validate(words[2], json.loads(payload))


