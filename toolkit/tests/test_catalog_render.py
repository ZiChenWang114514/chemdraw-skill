from __future__ import annotations

import posixpath
import re

from cdxml_toolkit.catalog import render

PAGES = render.render_all()


def test_the_four_layer_guides_recipes_and_shards_are_produced():
    assert {
        "interface-chemscript.md", "interface-com.md", "interface-cdxml-model.md", "interface-menu.md",
        "recipes-chemdraw.md",
    } <= set(PAGES)
    shards = [name for name in PAGES if name.startswith("inventory/")]
    assert any(name.startswith("inventory/chemscript-") for name in shards)
    assert any(name.startswith("inventory/com-") for name in shards)
    assert any(name.startswith("inventory/cdxml-attributes-") for name in shards)


def test_rendering_is_deterministic_and_marked_generated():
    again = render.render_all()

    assert again == PAGES
    for name, text in PAGES.items():
        assert "Generated by `cdx.py regen-catalog`" in text, name
        assert "\r" not in text and text.endswith("\n"), name


def test_shards_stay_loadable_in_one_read():
    for name, text in PAGES.items():
        if name.startswith("inventory/"):
            assert len(text.encode("utf-8")) <= render.SHARD_BYTES + 20_000, name


HANDWRITTEN = {"operations.md", "toolkit-tools.md", "mcp-signatures.md", "interface-catalog.md", "workflow-router.md"}


def test_every_link_between_generated_pages_resolves():
    for name, text in PAGES.items():
        for target in re.findall(r"\]\(([^)#]+\.md)\)", text):
            resolved = posixpath.normpath(posixpath.join(posixpath.dirname(name), target))
            assert resolved in PAGES or resolved in HANDWRITTEN, (name, target)


def test_guides_state_counts_the_tiers_and_how_to_reach_each_layer():
    chemscript = PAGES["interface-chemscript.md"]
    assert "execute_chemscript_sdk" in chemscript and "inspect_chemscript_sdk" in chemscript
    assert "T2" in chemscript and "recipes-chemdraw.md" in chemscript
    assert "Tier" in PAGES["interface-com.md"]
    menu = PAGES["interface-menu.md"]
    assert "Clean Up Structure" in menu and "356" in menu
    assert "no DTD" in PAGES["interface-cdxml-model.md"].replace("\n", " ")
    recipes = PAGES["recipes-chemdraw.md"]
    assert "chemscript-structure-properties" in recipes and '"op": "call_static"' in recipes
